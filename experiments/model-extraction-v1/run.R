#!/usr/bin/env Rscript

# Minimal, deterministic model-extraction experiment.
# The synthetic packet events are generated here; they are not a measured
# network trace and must not be used as evidence of real-world traffic fit.

args <- commandArgs(trailingOnly = TRUE)
output_dir <- if (length(args) >= 1L) args[[1L]] else file.path("artifacts", "model-extraction-v1")
dir.create(output_dir, recursive = TRUE, showWarnings = FALSE)

if (!requireNamespace("trafficmsd", quietly = TRUE)) {
  stop("Install trafficmsd first (for example: R CMD INSTALL .).")
}
if (!requireNamespace("jsonlite", quietly = TRUE)) {
  stop("The experiment requires jsonlite.")
}

# A small, deterministic packet-event fixture with empty time bins.
events <- data.frame(
  Time = c(0.10, 0.30, 1.15, 3.10, 3.40, 5.20, 8.10, 8.25, 8.80,
           13.10, 16.20, 16.60, 21.10, 25.10, 25.40, 31.10),
  Length = c(100, 80, 120, 90, 70, 140, 60, 80, 100,
             110, 75, 95, 160, 90, 120, 130)
)

sample_count <- 32L
bin_index <- as.integer(floor(events$Time))
signal <- vapply(
  0:(sample_count - 1L),
  function(index) sum(events$Length[bin_index == index]),
  numeric(1)
)
names(signal) <- NULL

decomposition <- trafficmsd::decompose_traffic(signal, cutoff.fraction = 0.004)
reconstructed <- as.numeric(trafficmsd::reconstruct_traffic(decomposition))

model_path <- file.path(output_dir, "model-v1.json")
model <- trafficmsd::export_model_v1(
  decomposition,
  observed_sample_count = length(signal),
  model_id = "synthetic-packet-events-32",
  dataset_id = "synthetic-packet-events-v1",
  path = model_path,
  time_unit = "second",
  time_unit_status = "verified",
  sampling_interval = 1,
  time_origin = 0,
  value_unit = "bytes",
  value_unit_status = "verified",
  cutoff_fraction = decomposition$cutoff.fraction,
  license_status = "verified",
  source_reference = "Generated deterministically by experiments/model-extraction-v1/run.R",
  preprocessing = c(
    "synthetic packet events generated by the experiment script",
    "bin index = floor(packet timestamp / 1 second)",
    "sum packet Length values per bin",
    "empty bins filled with zero"
  )
)

acf_at_lag <- function(x, lag) {
  centered <- x - mean(x)
  denominator <- sum(centered^2)
  if (denominator == 0) return(NA_real_)
  n <- length(centered)
  sum(centered[seq_len(n - lag)] * centered[(lag + 1L):n]) / denominator
}

quantile_summary <- function(x) {
  values <- stats::quantile(x, probs = c(0.50, 0.90, 0.95, 0.99),
                            names = FALSE, type = 7)
  as.list(stats::setNames(as.numeric(values), c("p50", "p90", "p95", "p99")))
}

wasserstein_1 <- function(x, y) {
  mean(abs(sort(x) - sort(y)))
}

ks_distance <- function(x, y) {
  points <- sort(unique(c(x, y)))
  max(abs(vapply(points, function(value) mean(x <= value), numeric(1)) -
          vapply(points, function(value) mean(y <= value), numeric(1))))
}

run_lengths <- function(x, threshold) {
  runs <- rle(x > threshold)
  as.integer(runs$lengths[runs$values])
}

optional_quantile <- function(x, probability) {
  if (length(x) == 0L) return(NULL)
  as.numeric(stats::quantile(x, probability, names = FALSE, type = 7))
}

source_mean <- mean(signal)
reconstruction_mean <- mean(reconstructed)
errors <- reconstructed - signal
source_volume <- sum(signal)
relative_l1 <- if (source_volume == 0) NULL else sum(abs(errors)) / source_volume
volume_error <- if (source_volume == 0) NULL else
  (sum(reconstructed) - source_volume) / source_volume

eligible_lags <- c(1L, 2L, 4L, 8L, 16L, 32L, 64L, 128L, 256L)
eligible_lags <- eligible_lags[eligible_lags < length(signal) / 4]
source_acf <- vapply(eligible_lags, function(lag) acf_at_lag(signal, lag), numeric(1))
reconstruction_acf <- vapply(
  eligible_lags,
  function(lag) acf_at_lag(reconstructed, lag),
  numeric(1)
)
acf_differences <- abs(source_acf - reconstruction_acf)
acf_rows <- lapply(seq_along(eligible_lags), function(index) {
  list(
    lag = as.integer(eligible_lags[[index]]),
    source_acf = as.numeric(source_acf[[index]]),
    reconstruction_acf = as.numeric(reconstruction_acf[[index]]),
    absolute_difference = as.numeric(acf_differences[[index]])
  )
})

burst_threshold <- as.numeric(stats::quantile(signal, 0.95, names = FALSE, type = 7))
source_runs <- run_lengths(signal, burst_threshold)
reconstruction_runs <- run_lengths(reconstructed, burst_threshold)

model_json <- jsonlite::toJSON(model, auto_unbox = TRUE, pretty = TRUE,
                               null = "null", digits = NA)
serialized_model_bytes <- nchar(as.character(model_json), type = "bytes")
source_float64_bytes <- 8L * length(signal)

metrics <- list(
  fidelity = list(
    mae = mean(abs(errors)),
    rmse = sqrt(mean(errors^2)),
    bias = mean(errors),
    relative_l1_error = relative_l1,
    volume_error = volume_error
  ),
  distribution = list(
    source_mean = source_mean,
    reconstruction_mean = reconstruction_mean,
    source_sd = stats::sd(signal),
    reconstruction_sd = stats::sd(reconstructed),
    source_quantiles = quantile_summary(signal),
    reconstruction_quantiles = quantile_summary(reconstructed),
    wasserstein_1 = wasserstein_1(signal, reconstructed),
    ks_distance = ks_distance(signal, reconstructed)
  ),
  temporal = list(
    acf_differences = acf_rows,
    mean_absolute_acf_difference = if (length(acf_differences) == 0L) {
      NULL
    } else {
      mean(acf_differences)
    }
  ),
  bursts = list(
    threshold = burst_threshold,
    source_exceedance_fraction = mean(signal > burst_threshold),
    reconstruction_exceedance_fraction = mean(reconstructed > burst_threshold),
    source_run_count = length(source_runs),
    reconstruction_run_count = length(reconstruction_runs),
    source_median_run_length = optional_quantile(source_runs, 0.50),
    reconstruction_median_run_length = optional_quantile(reconstruction_runs, 0.50),
    source_p95_run_length = optional_quantile(source_runs, 0.95),
    reconstruction_p95_run_length = optional_quantile(reconstruction_runs, 0.95),
    source_max_run_length = if (length(source_runs) == 0L) NULL else max(source_runs),
    reconstruction_max_run_length = if (length(reconstruction_runs) == 0L) {
      NULL
    } else {
      max(reconstruction_runs)
    }
  ),
  compactness = list(
    component_count = length(model$components),
    scale_zero_residual_count = sum(vapply(
      model$components,
      function(component) identical(component$scale_index, 0L),
      logical(1)
    )),
    serialized_model_bytes = as.integer(serialized_model_bytes),
    source_float64_bytes = as.integer(source_float64_bytes),
    model_size_ratio = serialized_model_bytes / source_float64_bytes
  )
)

commit <- tryCatch(
  {
    value <- system2("git", c("rev-parse", "HEAD"), stdout = TRUE, stderr = FALSE)
    if (length(value) == 1L && nchar(value) >= 7L) value else "local-unknown"
  },
  error = function(error) "local-unknown"
)

result <- list(
  schema_version = "1.0",
  experiment_id = "synthetic-model-extraction-v1",
  software = list(
    trafficmsd_version = as.character(utils::packageVersion("trafficmsd")),
    trafficmsd_commit = commit,
    model_schema_version = "1.0"
  ),
  dataset = list(
    dataset_id = "synthetic-packet-events-v1",
    source_reference = "Generated deterministically by experiments/model-extraction-v1/run.R",
    license_status = "verified",
    source_files = list()
  ),
  preprocessing = list(
    quantity = "sum_of_packet_lengths",
    aggregation = "sum",
    sampling_interval = 1,
    time_unit = "second",
    value_unit = "bytes",
    bin_convention = "left_closed_right_open",
    selection_policy = "all synthetic events; bin by floor(timestamp / 1 second)",
    preprocessing_version = "synthetic-packet-events-v1"
  ),
  configuration = list(
    cutoff_fraction = decomposition$cutoff.fraction,
    evaluation_split = "full_trace_diagnostic",
    training_range = NULL,
    test_range = NULL,
    random_seed = NULL
  ),
  results = list(list(
    trace_id = "synthetic-packet-events-32",
    status = "success",
    sample_count = length(signal),
    metrics = metrics
  )),
  summary = list(
    successful_traces = 1L,
    failed_traces = 0L,
    metric_medians = list(
      mae = metrics$fidelity$mae,
      rmse = metrics$fidelity$rmse,
      relative_l1_error = metrics$fidelity$relative_l1_error,
      volume_error = metrics$fidelity$volume_error,
      wasserstein_1 = metrics$distribution$wasserstein_1,
      mean_absolute_acf_difference = metrics$temporal$mean_absolute_acf_difference,
      model_size_ratio = metrics$compactness$model_size_ratio
    ),
    metric_iqrs = list(
      mae = 0,
      rmse = 0,
      relative_l1_error = if (is.null(metrics$fidelity$relative_l1_error)) NULL else 0,
      volume_error = if (is.null(metrics$fidelity$volume_error)) NULL else 0,
      wasserstein_1 = 0,
      mean_absolute_acf_difference = if (
        is.null(metrics$temporal$mean_absolute_acf_difference)
      ) NULL else 0,
      model_size_ratio = 0
    )
  )
)

jsonlite::write_json(
  result,
  file.path(output_dir, "evaluation-result-v1.json"),
  auto_unbox = TRUE,
  pretty = TRUE,
  null = "null",
  digits = NA
)
write.csv(
  data.frame(sample_index = 0:(length(signal) - 1L), value = signal),
  file.path(output_dir, "source-signal.csv"),
  row.names = FALSE
)
write.csv(
  data.frame(sample_index = 0:(length(reconstructed) - 1L), value = reconstructed),
  file.path(output_dir, "reconstructed-signal.csv"),
  row.names = FALSE
)

message("Synthetic model-extraction experiment completed: ", output_dir)
